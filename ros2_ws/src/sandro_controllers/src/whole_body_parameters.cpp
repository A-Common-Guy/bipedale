bool set_whole_body_parameter(WholeBodyParameters &parameters,
                              const std::string &name, const double value) {
  if (name == kWholeBodyGainPointsName) {
    parameters.gain_table_points = static_cast<int>(value);
    return true;
  }
  for (const auto &entry : whole_body_double_parameters()) {
    if (name == entry.name) {
      entry.field(parameters) = value;
      return true;
    }
  }
  return false;
}

